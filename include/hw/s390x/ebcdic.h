/* Fixed text (names, identifiers, LOADPARM) uses code page 037. */
#define ebcdic2ascii ebcdic2latin1_037
#define ascii2ebcdic latin12ebcdic_037

static inline bool ebcdic_codepage_valid(uint32_t codepage)
{
    return codepage == EBCDIC_CP037 || codepage == EBCDIC_CP500;
}

static inline const uint8_t *ebcdic_to_latin1_table(uint32_t codepage)
{
    return codepage == EBCDIC_CP500 ? ebcdic2latin1_500 : ebcdic2latin1_037;
}

static inline const uint8_t *latin1_to_ebcdic_table(uint32_t codepage)
{
    return codepage == EBCDIC_CP500 ? latin12ebcdic_500 : latin12ebcdic_037;
}

/* Convert ISO 8859-1 text to EBCDIC in the given code page. */
static inline void ebcdic_put_cp(uint32_t codepage, uint8_t *p,
                                 const char *ascii, int len)
{
    const uint8_t *table = latin1_to_ebcdic_table(codepage);
    int i;

    for (i = 0; i < len; i++) {
        p[i] = table[(uint8_t)ascii[i]];
    }
}

/* Convert EBCDIC text in the given code page to ISO 8859-1. */
static inline void ascii_put_cp(uint32_t codepage, uint8_t *p,
                                const char *ebcdic, int len)
{
    const uint8_t *table = ebcdic_to_latin1_table(codepage);
    int i;

    for (i = 0; i < len; i++) {
        p[i] = table[(uint8_t)ebcdic[i]];
    }
}

static inline void ebcdic_put(uint8_t *p, const char *ascii, int len)
{
    ebcdic_put_cp(EBCDIC_CP037, p, ascii, len);
}

static inline void ascii_put(uint8_t *p, const char *ebcdic, int len)
{
    ascii_put_cp(EBCDIC_CP037, p, ebcdic, len);
}

/*
 * Consoles convert between the guest's EBCDIC and ISO 8859-1, and carry
 * UTF-8 on their character device.
 */

/* Encode ISO 8859-1 text as UTF-8; @out has room for 2 * @len bytes. */
static inline int latin1_to_utf8(uint8_t *out, const uint8_t *in, int len)
{
    int i, n = 0;

    for (i = 0; i < len; i++) {
        if (in[i] < 0x80) {
            out[n++] = in[i];
        } else {
            out[n++] = 0xc0 | (in[i] >> 6);
            out[n++] = 0x80 | (in[i] & 0x3f);
        }
    }
    return n;
}

typedef struct Utf8Decoder {
    uint32_t ch;        /* character being decoded */
    uint8_t pending;    /* continuation bytes still expected */
} Utf8Decoder;

/*
 * Decode one byte of UTF-8 input.  Returns the ISO 8859-1 character once a
 * character is complete, '?' for a character outside ISO 8859-1 or
 * malformed input, or -1 while more bytes are needed.
 */
static inline int utf8_decode_latin1(Utf8Decoder *d, uint8_t byte)
{
    if (d->pending) {
        if ((byte & 0xc0) == 0x80) {
            d->ch = (d->ch << 6) | (byte & 0x3f);
            if (--d->pending) {
                return -1;
            }
            return d->ch <= 0xff ? d->ch : '?';
        }
        /* Truncated sequence: drop it and take this byte afresh. */
        d->pending = 0;
    }
    if (byte < 0x80) {
        return byte;
    }
    if (byte >= 0xc2 && byte <= 0xdf) {
        d->ch = byte & 0x1f;
        d->pending = 1;
    } else if (byte >= 0xe0 && byte <= 0xef) {
        d->ch = byte & 0x0f;
        d->pending = 2;
    } else if (byte >= 0xf0 && byte <= 0xf4) {
        d->ch = byte & 0x07;
        d->pending = 3;
    } else {
        return '?';
    }
    return -1;
}

